#!/usr/bin/env python3
"""Minimal OpenAI-compatible mock endpoint for exercising the ``llm`` brief backend.

It is NOT a language model. It reads the ALLOWED technique ids and the plan
phases from the request and returns a contract-shaped JSON narration that cites
only allowed ids - demonstrating the strict JSON contract and citation guard
without any network access or API key.

Run it in one terminal::

    python scripts/mock_llm_server.py --port 8765

and in another::

    AISEC_LLM_URL=http://127.0.0.1:8765/v1/chat/completions AISEC_LLM_KEY=test \\
        python -m aep brief --plan plans/ransomware-affiliate-plan.json --backend llm

Pass ``--rogue`` to make the mock cite a technique that is NOT in the plan, so
you can watch the narrator reject it and fall back to the template backend.
"""

from __future__ import annotations

import argparse
import json
import re
from http.server import BaseHTTPRequestHandler, HTTPServer

CITATION_RE = re.compile(r"T\d{4}(?:\.\d{3})?")
ROGUE = False


class Handler(BaseHTTPRequestHandler):
    """Answer chat-completions requests with contract-shaped JSON."""

    def log_message(self, *args) -> None:  # noqa: D401 - silence default logging
        return

    def do_POST(self) -> None:  # noqa: N802 - http.server naming
        length = int(self.headers.get("Content-Length", "0"))
        body = json.loads(self.rfile.read(length) or b"{}")
        user = body["messages"][1]["content"]

        allowed_line = user.splitlines()[0]
        allowed = CITATION_RE.findall(allowed_line)
        plan = {}
        if "PLAN:" in user:
            try:
                plan = json.loads(user.split("PLAN:", 1)[1].strip())
            except json.JSONDecodeError:
                plan = {}

        scenes = []
        for phase in plan.get("phases", []):
            tids = [t["id"] for t in phase.get("techniques", [])]
            scenes.append({
                "scene": phase["phase"].replace("-", " ").title(),
                "narrative": (
                    f"The emulated actor works through the "
                    f"{phase['phase'].replace('-', ' ')} phase."),
                "inject": "Facilitator runs the mapped Atomic tests in the lab.",
                "soc_expectation": "Analysts confirm telemetry and alerting.",
                "techniques": tids,
            })
        if not scenes:
            scenes = [{"scene": "Overview", "narrative": "Emulation overview.",
                       "inject": "n/a", "soc_expectation": "n/a",
                       "techniques": allowed[:3]}]

        citations = list(allowed)
        if ROGUE:
            # Inject an out-of-plan citation to prove the guard works.
            citations.append("T9999")
            scenes[0]["techniques"].append("T9999")

        content = {
            "executive_brief": (
                "Mock-model executive brief: this authorized purple-team exercise "
                f"emulates {len(allowed)} ATT&CK techniques to validate SOC "
                "detection coverage. (Generated by the offline mock endpoint.)"),
            "tabletop_scenario": scenes,
            "citations": citations,
        }
        reply = {"choices": [{"message": {"role": "assistant",
                                          "content": json.dumps(content)}}]}
        data = json.dumps(reply).encode("utf-8")
        self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)


def main() -> None:
    global ROGUE
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--port", type=int, default=8765)
    ap.add_argument("--host", default="127.0.0.1")
    ap.add_argument("--rogue", action="store_true",
                    help="cite an out-of-plan technique to trigger the guard")
    args = ap.parse_args()
    ROGUE = args.rogue
    server = HTTPServer((args.host, args.port), Handler)
    print(f"mock LLM endpoint on http://{args.host}:{args.port}/v1/chat/completions "
          f"(rogue={ROGUE})")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        server.shutdown()


if __name__ == "__main__":
    main()
